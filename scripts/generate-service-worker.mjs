import { createHash } from 'node:crypto'
import { readFile, readdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const PROJECT_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const DIST_DIR = path.join(PROJECT_ROOT, 'dist')

export function computeBuildId(files) {
  const hash = createHash('sha256')
  for (const file of [...files].sort((a, b) => a.path.localeCompare(b.path))) {
    hash.update(file.path)
    hash.update('\0')
    hash.update(file.content)
    hash.update('\0')
  }
  return hash.digest('hex').slice(0, 16)
}

export function renderServiceWorker({ buildId, precacheUrls }) {
  const urls = JSON.stringify([...new Set(precacheUrls)].sort(), null, 2)
  return `// Generated by scripts/generate-service-worker.mjs. Do not edit.\n` +
`const BUILD_ID = ${JSON.stringify(buildId)};
const SHELL_CACHE = \`xiaole-shell-\${BUILD_ID}\`;
const ASSET_CACHE = \`xiaole-assets-\${BUILD_ID}\`;
const CURRENT_CACHES = new Set([SHELL_CACHE, ASSET_CACHE]);
const PRECACHE_URLS = ${urls};
const PRECACHE_ASSETS = PRECACHE_URLS.filter((url) => url.startsWith('/assets/'));
const PRECACHE_SHELL = PRECACHE_URLS.filter((url) => !url.startsWith('/assets/'));

self.addEventListener('install', (event) => {
  event.waitUntil(
    Promise.all([
      caches.open(SHELL_CACHE).then((cache) => cache.addAll(PRECACHE_SHELL)),
      caches.open(ASSET_CACHE).then((cache) => cache.addAll(PRECACHE_ASSETS))
    ])
      .then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((names) => Promise.all(
        names
          .filter((name) =>
            (name.startsWith('xiaole-ai-') || name.startsWith('xiaole-shell-') || name.startsWith('xiaole-assets-')) &&
            !CURRENT_CACHES.has(name)
          )
          .map((name) => caches.delete(name))
      ))
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;

  const url = new URL(request.url);
  if (url.origin !== self.location.origin || isApiPath(url.pathname)) return;

  if (request.mode === 'navigate') {
    event.respondWith(networkFirstNavigation(request));
    return;
  }

  if (url.pathname.startsWith('/assets/')) {
    event.respondWith(cacheFirstCurrentAsset(request));
    return;
  }

  event.respondWith(staleWhileRevalidate(request));
});

function isApiPath(pathname) {
  return ['/api/', '/v1/', '/token', '/health', '/ws', '/sessions', '/session', '/messages',
    '/chat/', '/uploads', '/files', '/vision', '/documents', '/memory', '/voice', '/static',
    '/analytics', '/tasks', '/tools', '/feedback', '/faces', '/dashboard', '/schedule']
    .some((prefix) => pathname === prefix.replace(/\\/$/, '') || pathname.startsWith(prefix));
}

async function networkFirstNavigation(request) {
  try {
    const response = await fetch(new Request(request, { cache: 'no-store' }));
    if (response && response.ok) {
      const cache = await caches.open(SHELL_CACHE);
      await cache.put('/index.html', response.clone());
      await cache.put('/', response.clone());
    }
    return response;
  } catch (error) {
    return (await caches.match('/index.html')) || (await caches.match('/')) || Promise.reject(error);
  }
}

async function cacheFirstCurrentAsset(request) {
  const cache = await caches.open(ASSET_CACHE);
  const cached = await cache.match(request);
  if (cached) return cached;
  const response = await fetch(request);
  if (response && response.ok && response.type === 'basic') await cache.put(request, response.clone());
  return response;
}

async function staleWhileRevalidate(request) {
  const cache = await caches.open(SHELL_CACHE);
  const cached = await cache.match(request);
  const network = fetch(request).then(async (response) => {
    if (response && response.ok && response.type === 'basic') await cache.put(request, response.clone());
    return response;
  });
  return cached || network;
}

self.addEventListener('push', (event) => {
  if (!event.data) return;
  const data = event.data.json();
  event.waitUntil(self.registration.showNotification(data.title || '小乐 AI', {
    body: data.body || '你有新消息',
    icon: '/favicon-dark.png',
    badge: '/favicon-dark.png',
    vibrate: [100, 50, 100],
    data: { url: data.url || '/' }
  }));
});

self.addEventListener('notificationclick', (event) => {
  event.notification.close();
  const target = event.notification.data?.url || '/';
  event.waitUntil(self.clients.matchAll({ type: 'window' }).then((windows) => {
    const existing = windows.find((client) => client.url.includes(self.location.origin) && 'focus' in client);
    return existing ? existing.focus() : self.clients.openWindow?.(target);
  }));
});
`
}

export async function generateServiceWorker(distDir = DIST_DIR) {
  const files = await collectBuildFiles(distDir)
  const buildId = computeBuildId(files)
  const indexHtml = files.find((file) => file.path === '/index.html')?.content.toString('utf8') || ''
  const entryAssets = [...indexHtml.matchAll(/(?:src|href)=["'](\/assets\/[^"']+)["']/g)]
    .map((match) => match[1])
  const precacheUrls = [
    '/',
    '/index.html',
    '/manifest.json',
    '/favicon-dark.png',
    '/favicon-light.png',
    '/logo-xiaole.svg',
    ...entryAssets
  ]
  await writeFile(path.join(distDir, 'sw.js'), renderServiceWorker({ buildId, precacheUrls }))
  return { buildId, precacheUrls }
}

async function collectBuildFiles(distDir) {
  const names = await walk(distDir)
  const selected = names.filter((name) => name === 'index.html' || name.startsWith('assets/'))
  return Promise.all(selected.map(async (name) => ({
    path: `/${name}`,
    content: await readFile(path.join(distDir, name))
  })))
}

async function walk(root, relative = '') {
  const entries = await readdir(path.join(root, relative), { withFileTypes: true })
  const nested = await Promise.all(entries.map((entry) => {
    const name = path.posix.join(relative, entry.name)
    return entry.isDirectory() ? walk(root, name) : [name]
  }))
  return nested.flat()
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const result = await generateServiceWorker()
  console.log(`Generated Service Worker for build ${result.buildId}`)
}
